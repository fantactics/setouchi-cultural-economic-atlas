export function applyEssayEditorialOverride(article){
  const patch=essayOverrides[article.slug];
  if(!patch) return article;
  const extraSources=patch.extraSources || [];
  const sourceIds=new Set((article.sources || []).map((source)=>source.id));
  const mergedSources=[...(article.sources || []),...extraSources.filter((source)=>!sourceIds.has(source.id))];
  const {extraSources:_,...editorialPatch}=patch;
  return {...article,...editorialPatch,sources:mergedSources};
}
