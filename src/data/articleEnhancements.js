export function enhanceBookArticle(article){
  const patch=articleEnhancements[article.slug];
  if(!patch) return article;

  const headingMap=patch.sectionHeadingReplacements || {};
  const paragraphMap=patch.sectionParagraphReplacements || {};
  const originalSections=(article.sections || []).map((section)=>{
    const originalHeading=section.heading;
    return {
      ...section,
      ...(headingMap[originalHeading] ? {heading:headingMap[originalHeading]} : {}),
      ...(paragraphMap[originalHeading] ? {paragraphs:paragraphMap[originalHeading]} : {})
    };
  });

  const existingSourceIds=new Set((article.sources || []).map((source)=>source.id));
  const extraSources=(patch.sources || []).filter((source)=>!existingSourceIds.has(source.id));
  const keywords=[...new Set([...(article.keywords || []),...(patch.keywords || [])])];

  return {
    ...article,
    ...(patch.lead ? {lead:patch.lead} : {}),
    keywords,
    sections:[...(patch.prependSections || []),...originalSections],
    sources:[...(article.sources || []),...extraSources]
  };
}
